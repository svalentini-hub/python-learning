print("Welcome to the python calculator! Give me two numbers and I will print their sum, difference, product and division!")
number_1 = float(input("Tell me the first number: "))
number_2 = float(input("tell me the second number: "))

total_sum = number_1 + number_2
difference = number_1 - number_2
product = number_1 * number_2
division = number_1 / number_2

print(f"Alright, here are the results:\n The sum: {total_sum}\n The difference: {difference}\n The product: {product}\n The division: {division}")